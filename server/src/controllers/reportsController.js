import PDFDocument from 'pdfkit';
import { analysisStore } from '../models/dataStore.js';

export const getReports = async (req, res) => {
  try {
    if (!req.user?._id) {
      return res.status(401).json({ message: 'Authentication required to access reports' });
    }

    const filter = { userId: req.user._id };
    if (req.query.type && req.query.type !== 'all') {
      filter.type = req.query.type.toLowerCase();
    }

    const items = await analysisStore.find(filter);
    const reports = items.map((item) => ({
      _id: item._id,
      title: item.title,
      type: item.type,
      classification: item.classification,
      trustScore: item.trustScore,
      summary: item.summary,
      createdAt: item.createdAt,
    }));

    return res.json({ reports });
  } catch (error) {
    return res.status(500).json({ message: error.message });
  }
};

export const downloadReport = async (req, res) => {
  try {
    if (!req.user?._id) {
      return res.status(401).json({ message: 'Authentication required' });
    }

    const item = await analysisStore.findById(req.params.id);
    if (!item) {
      return res.status(404).json({ message: 'Report not found' });
    }

    const isOwner = item.userId && String(item.userId) === String(req.user._id);
    const isAdmin = req.user.role === 'admin';
    if (!isOwner && !isAdmin) {
      return res.status(404).json({ message: 'Report not found' });
    }

    // Generate real PDF report
    const doc = new PDFDocument({ margin: 40, size: 'A4' });
    const filename = `Meiora_Report_${item.type}_${Date.now()}.pdf`;

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);

    doc.pipe(res);

    // Header
    doc.fillColor('#6C5CE7').fontSize(22).font('Helvetica-Bold').text('MEIORA AI', 40, 40);
    doc.fillColor('#666666').fontSize(10).font('Helvetica').text('Intelligence & Verification Platform', 40, 66);
    doc.moveDown(1.5);

    // Divider line
    doc.strokeColor('#E0E0E0').lineWidth(1).moveTo(40, 85).lineTo(555, 85).stroke();
    doc.moveDown(2);

    // Title & Meta
    doc.fillColor('#1A1C29').fontSize(16).font('Helvetica-Bold').text(item.title || 'Analysis Report', 40, 100);
    doc.fillColor('#888888').fontSize(9).font('Helvetica').text(
      `Analysis Type: ${item.type.toUpperCase()}  |  Date: ${new Date(item.createdAt).toLocaleString()}  |  ID: ${item._id}`,
      40,
      122
    );

    // Score & Classification Box
    doc.roundedRect(40, 145, 515, 60, 6).fill('#F8F9FE');
    doc.fillColor('#6C5CE7').fontSize(26).font('Helvetica-Bold').text(`${item.trustScore}%`, 60, 160);
    doc.fillColor('#888888').fontSize(9).font('Helvetica').text('TRUST SCORE', 60, 190);

    doc.fillColor('#1A1C29').fontSize(18).font('Helvetica-Bold').text(item.classification, 220, 160);
    doc.fillColor('#888888').fontSize(9).font('Helvetica').text(`CONFIDENCE: ${item.confidence || 0}%`, 220, 185);

    // Executive Summary
    let currentY = 225;
    if (item.summary) {
      doc.fillColor('#1A1C29').fontSize(12).font('Helvetica-Bold').text('Executive Summary', 40, currentY);
      currentY += 18;
      doc.fillColor('#444444').fontSize(10).font('Helvetica').text(item.summary, 40, currentY, { width: 515, lineGap: 3 });
      currentY = doc.y + 15;
    }

    // AI Explanation
    if (item.explanation) {
      doc.fillColor('#1A1C29').fontSize(12).font('Helvetica-Bold').text('Detailed Assessment', 40, currentY);
      currentY += 18;
      doc.fillColor('#444444').fontSize(10).font('Helvetica').text(item.explanation, 40, currentY, { width: 515, lineGap: 3 });
      currentY = doc.y + 15;
    }

    // Key Indicators
    if (item.keyIndicators && item.keyIndicators.length > 0) {
      doc.fillColor('#1A1C29').fontSize(12).font('Helvetica-Bold').text('Key Indicators', 40, currentY);
      currentY += 18;
      item.keyIndicators.forEach((ind) => {
        const bullet = ind.type === 'positive' ? '[+]' : ind.type === 'negative' ? '[-]' : '[*]';
        doc.fillColor('#333333').fontSize(9).font('Helvetica').text(`${bullet} ${ind.text}`, 50, currentY, { width: 505 });
        currentY = doc.y + 4;
      });
      currentY += 10;
    }

    // Evidence
    if (item.evidence && item.evidence.length > 0) {
      doc.fillColor('#1A1C29').fontSize(12).font('Helvetica-Bold').text('Evidence & Citations', 40, currentY);
      currentY += 18;
      item.evidence.forEach((ev) => {
        doc.fillColor('#333333').fontSize(9).font('Helvetica').text(`- ${ev.text || ev.summary} (${ev.sourceName || ev.source || 'Cited'})`, 50, currentY, { width: 505 });
        currentY = doc.y + 4;
      });
    }

    // Footer
    doc.fillColor('#AAAAAA').fontSize(8).font('Helvetica').text(
      'Generated by Meiora AI — Real-time Fake News & Brand Sentiment Verification. Based on evidentiary fact evaluation.',
      40,
      780,
      { align: 'center', width: 515 }
    );

    doc.end();
  } catch (error) {
    console.error('Error generating PDF:', error);
    return res.status(500).json({ message: error.message });
  }
};
